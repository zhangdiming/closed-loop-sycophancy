import argparse, json, pathlib, re, sys, torch
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "data/pub_prompts"))
from unicorn_prompts import PROMPT_GALLERY
from omniverifier_prompt import ov_question

UG_OUT = "This image is generated by a prompt: {prompt}. Does this image accurately represent the prompt? Please answer yes or no."
UG_COTV = ("This image is generated by a prompt: {prompt}. Please assess the image generation quality step by step. First, breakdown the "
           "prompt into multiple visual questions and iteratively answer each question with Yes or No between <think_start> <think_end>. "
           "Questions should cover all-round details about whether the image accurately represents entity categories, counting of "
           "entities, color, spatial relationship in the prompt. Next, output the final result between <answer_start> <answer_end>. "
           "Output Yes if all multi-choice answers equal yes to show the image has accurate alignment with the prompt. Otherwise answer with No.")
DECOMP = ("Break down the following text-to-image prompt into multiple simple visual yes/no questions. The questions should cover the "
          "entity categories, the counting of entities, the colors, and the spatial relationships in the prompt. Ask only about what the "
          "prompt states, so that every answer is yes if the image follows the prompt. Write one question per line and nothing else.\n"
          "Prompt: {prompt}")
UC_CAT = {"counting": "numeracy", "position": "spatio", "color_attr": "relation"}
TAGS = ("position", "color_attr", "counting")


class Backend:
    def __init__(self, judge):
        from mucg.adapters.base import load
        self.name = judge; self.A = load(judge)

    @torch.no_grad()
    def yn(self, img, text, prior=None):
        r = self.A.judge(img, text, prior_prompt=prior) if prior else self.A.judge(img, text)
        return r["p_yes"]

    @torch.no_grad()
    def gen(self, img, text, n):
        A = self.A
        if self.name.startswith("janus"):
            if img is None:
                conv = [{"role": "<|User|>", "content": text}, {"role": "<|Assistant|>", "content": ""}]
                sft = A.proc.apply_sft_template_for_multi_turn_prompts(conversations=conv, sft_format=A.proc.sft_format, system_prompt=A.proc.system_prompt)
                ids = torch.tensor([A.tok.encode(sft)], device=A.device)
                emb = A.model.language_model.get_input_embeddings()(ids); att = torch.ones_like(ids)
            else:
                conv = [{"role": "<|User|>", "content": f"<image_placeholder>\n{text}", "images": [img]}, {"role": "<|Assistant|>", "content": ""}]
                inp = A.proc(conversations=conv, images=[img], force_batchify=True).to(A.device)
                emb = A.model.prepare_inputs_embeds(**inp); att = inp.attention_mask
            out = A.model.language_model.generate(inputs_embeds=emb, attention_mask=att, pad_token_id=A.tok.eos_token_id,
                                                  bos_token_id=A.tok.bos_token_id, eos_token_id=A.tok.eos_token_id,
                                                  max_new_tokens=n, do_sample=False, use_cache=True)
            return A.tok.decode(out[0], skip_special_tokens=True)
        if self.name == "bagel":
            from data.data_utils import pil_img2rgb
            inf = A.inf; ctx = inf.init_gen_context()
            with torch.autocast(device_type="cuda", enabled=True, dtype=torch.bfloat16):
                if img is not None: ctx = inf.update_context_image(inf.vae_transform.resize_transform(pil_img2rgb(img)), ctx, vae=False)
                ctx = inf.update_context_text(text, ctx)
                return inf.gen_text(ctx, max_length=n, do_sample=False)
        if self.name == "omnigen2":
            chat = A.chat; mllm = A.pipe.mllm
            t = chat._apply_chat_template(text, [img] if img is not None else None)
            inp = chat.prepare_inputs_for_text_generation(t, [img] if img is not None else None, mllm.device)
            out = mllm.generate(**inp, max_new_tokens=n, do_sample=False)
            return A.tok.decode(out[0][inp["input_ids"].shape[1]:], skip_special_tokens=True)
        raise ValueError(self.name)


def parse_json_field(text, field):
    t = text.replace("```json", "").replace("```", "")
    m = re.search(r"\{.*\}", t, re.S)
    if m:
        try: return json.loads(m.group(0)).get(field)
        except Exception: pass
    m = re.search(rf'"{field}"\s*:\s*"?([A-Za-z0-9.]+)', t)
    return m.group(1) if m else None


def parse_questions(text):
    qs = []
    for line in text.splitlines():
        line = re.sub(r"^\s*(\d+[.)]|[-*])\s*", "", line).strip()
        if line.endswith("?") and 3 < len(line) < 200: qs.append(line)
    return qs[:12]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--judge", required=True, choices=["bagel", "janus7b", "omnigen2"])
    ap.add_argument("--protocols", nargs="*", default=["ug_out", "dq_fresh", "dq_req", "dq_cl", "ov", "uc", "cotv"])
    ap.add_argument("--limit", type=int); ap.add_argument("--out_tag", default=""); ap.add_argument("--part", type=int, default=0); ap.add_argument("--nparts", type=int, default=1)
    a = ap.parse_args()
    B = Backend(a.judge)
    prompts = {r["pid"]: r for r in (json.loads(l) for l in open(ROOT / "data/prompts.jsonl", encoding="utf-8"))}
    gdir = ROOT / "runs/gen" / a.judge
    images = [r for r in (json.loads(l) for l in open(gdir / "manifest.jsonl")) if prompts[r["pid"]]["tag"] in TAGS and r["seed"] in (0, 1)]
    images = sorted(images, key=lambda r: r["image"])[a.part::a.nparts]
    if a.limit: images = images[: a.limit]
    out = ROOT / "runs/pub"; out.mkdir(parents=True, exist_ok=True)
    dpath = out / f"decomp_{a.judge}{a.out_tag}.json"
    dec = json.load(open(dpath)) if dpath.exists() else {}
    if any(p in ("dq_fresh", "dq_req", "dq_cl") for p in a.protocols):
        for r in images:
            if r["pid"] in dec: continue
            raw = B.gen(None, DECOMP.format(prompt=r["prompt"]), 200)
            dec[r["pid"]] = {"raw": raw, "questions": parse_questions(raw)}
            if a.nparts == 1: json.dump(dec, open(dpath, "w"), indent=1)
        if a.nparts > 1: json.dump(dec, open(out / f"decomp_{a.judge}_p{a.part}.json", "w"), indent=1)
    ext = {}
    if "dq_ext" in a.protocols:
        for fp in sorted(out.glob("decomp_qwen3vl*.json")): ext.update(json.load(open(fp)))
    of = out / (f"{a.judge}{a.out_tag}.jsonl" if a.part == 0 else f"{a.judge}{a.out_tag}_p{a.part}.jsonl")
    done = {(json.loads(l)["image"], json.loads(l)["protocol"]) for l in open(of)} if of.exists() else set()
    f = open(of, "a")
    for r in images:
        img = None; P = r["prompt"]; tag = prompts[r["pid"]]["tag"]
        for proto in a.protocols:
            if (r["image"], proto) in done: continue
            if img is None: img = Image.open(gdir / r["image"]).convert("RGB")
            row = {"judge": a.judge, "image": r["image"], "pid": r["pid"], "tag": tag, "protocol": proto}
            if proto == "ug_out": row["p_yes"] = B.yn(img, UG_OUT.format(prompt=P))
            elif proto in ("dq_fresh", "dq_req", "dq_cl"):
                qs = dec[r["pid"]]["questions"]; row["questions"] = qs
                fmt = lambda q: f"{q} Please answer yes or no."
                if proto == "dq_fresh": row["p_yes"] = [B.yn(img, fmt(q)) for q in qs]
                elif proto == "dq_req": row["p_yes"] = [B.yn(img, f"This image is generated by a prompt: {P}. " + fmt(q)) for q in qs]
                else: row["p_yes"] = [B.yn(img, fmt(q), prior=P) for q in qs]
            elif proto == "dq_ext":
                qs = ext[r["pid"]]["questions"]; row["questions"] = qs
                row["p_yes"] = [B.yn(img, f"{q} Please answer yes or no.") for q in qs]
            elif proto == "ov":
                t = B.gen(img, ov_question(P), 256); row["raw"] = t; row["answer"] = parse_json_field(t, "answer")
            elif proto == "uc":
                t = B.gen(img, PROMPT_GALLERY[UC_CAT[tag]].format(prompt=P, category=tag), 400); row["raw"] = t
                s = parse_json_field(t, "score")
                try: row["score"] = float(s)
                except (TypeError, ValueError): row["score"] = None
            elif proto == "cotv":
                t = B.gen(img, UG_COTV.format(prompt=P), 800); row["raw"] = t
                body = t.split("<think_end>")[0]
                ans = re.findall(r"\?[\s\-:*(]*(Yes|No|yes|no)\b", body)
                row["n_q"] = len(ans); row["frac_yes"] = (sum(x.lower() == "yes" for x in ans) / len(ans)) if ans else None
                m = re.search(r"<answer_start>\s*\**\s*(Yes|No|yes|no)", t)
                row["final"] = m.group(1).lower() if m else None
            f.write(json.dumps(row) + "\n"); f.flush()
    print("done", of)

if __name__ == "__main__":
    main()
